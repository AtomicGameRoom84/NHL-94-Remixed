#!/usr/bin/env python3
"""Carve the cartridge into data blobs plus the code already identified.

The invariant this exists to protect: the build is byte-exact from the
first commit, before a single instruction has been understood. With no
regions declared, the whole ROM is one `incbin` and the rebuild is
trivially identical. Each region added replaces a slice of that blob
with committed assembly, and the rebuild either still matches or the
region is wrong -- there is no state in between, and no way to drift.

That is the opposite of disassembling outward from the entry points and
measuring how much was reached. Coverage here only ever goes up, and a
mistake is a failed build rather than a subtly wrong ROM.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from romcheck import DEFAULT_LOCK, RomError, identify  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def load_regions(path: Path, rom_size: int, entry_id: str) -> list[dict]:
    doc = json.loads(path.read_text())
    if doc.get("rom") != entry_id:
        raise RomError(
            f"{path.name} describes '{doc.get('rom')}' but the supplied "
            f"cartridge is '{entry_id}'. Regions are revision-specific; "
            f"addresses from one revision are wrong for another."
        )
    regions = sorted(doc.get("regions", []), key=lambda r: int(r["at"], 16))

    previous_end = 0
    for region in regions:
        at, size = int(region["at"], 16), region["size"]
        name = region.get("name", f"at {region['at']}")
        if size <= 0:
            raise RomError(f"region {name}: size must be positive")
        if at < previous_end:
            raise RomError(
                f"region {name} starts at 0x{at:06x}, inside the region that "
                f"ends at 0x{previous_end:06x}. Overlapping regions would "
                f"emit the same bytes twice."
            )
        if at + size > rom_size:
            raise RomError(
                f"region {name} runs to 0x{at + size:06x}, past the end of a "
                f"{rom_size:,}-byte cartridge."
            )
        source = ROOT / region["source"]
        if not source.is_file():
            raise RomError(f"region {name}: no such source file {region['source']}")
        if not region.get("evidence"):
            raise RomError(
                f"region {name}: every region needs an 'evidence' field saying "
                f"how its address was established. A region with no provenance "
                f"is a guess, and guesses are what this project is replacing."
            )
        previous_end = at + size
    return regions


def split(rom_path: Path, regions_path: Path, out_dir: Path,
          lock_path: Path = DEFAULT_LOCK) -> dict:
    entry = identify(rom_path, lock_path)
    rom = rom_path.read_bytes()
    regions = load_regions(regions_path, len(rom), entry["id"])

    data_dir = out_dir / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    for stale in data_dir.glob("*.bin"):
        stale.unlink()

    lines = [
        "; Generated by tools/split.py from the user's own cartridge.",
        "; Do not hand-edit and do not commit: this file names local blobs",
        "; carved out of copyrighted data.",
        "",
    ]
    covered = 0

    def emit_data(start: int, end: int) -> None:
        nonlocal covered
        if end <= start:
            return
        blob = data_dir / f"{start:06x}.bin"
        blob.write_bytes(rom[start:end])
        lines.append(f'\tincbin\t"{blob.resolve().as_posix()}"'
                     f'\t; 0x{start:06x}-0x{end:06x} ({end - start:,} bytes)')
        covered += end - start

    cursor = 0
    for region in regions:
        at, size = int(region["at"], 16), region["size"]
        emit_data(cursor, at)
        lines.append("")
        lines.append(f"; 0x{at:06x}-0x{at + size:06x}  {region.get('name', '')}")
        lines.append(f"; evidence: {region['evidence']}")
        lines.append(f'\tinclude\t"{(ROOT / region["source"]).resolve().as_posix()}"')
        lines.append("")
        covered += size
        cursor = at + size
    emit_data(cursor, len(rom))

    if covered != len(rom):
        raise RomError(
            f"internal error: generated includes cover {covered:,} of "
            f"{len(rom):,} bytes. Refusing to write a build that cannot "
            f"reproduce the cartridge."
        )

    inc = out_dir / "regions.inc"
    inc.write_text("\n".join(lines) + "\n")
    return {"rom": entry["id"], "size": len(rom), "regions": len(regions),
            "code_bytes": sum(r["size"] for r in regions),
            "data_blobs": len(list(data_dir.glob("*.bin"))), "inc": inc}


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--rom", default=str(ROOT / "rom" / "nhl94.md"))
    p.add_argument("--regions", default=str(ROOT / "src" / "regions.json"))
    p.add_argument("--out", default=str(ROOT / "build"))
    p.add_argument("--lock", default=str(DEFAULT_LOCK),
                   help="rom-lock.json to identify the cartridge against")
    a = p.parse_args()
    try:
        r = split(Path(a.rom), Path(a.regions), Path(a.out), Path(a.lock))
    except RomError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    pct = 100 * r["code_bytes"] / r["size"]
    print(f"Cartridge      : {r['rom']} ({r['size']:,} bytes)")
    print(f"Code regions   : {r['regions']} ({r['code_bytes']:,} bytes, {pct:.2f}%)")
    print(f"Data blobs     : {r['data_blobs']}")
    print(f"Wrote          : {r['inc']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
