import hashlib
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "toolkit"))
sys.path.insert(0, str(ROOT / "toolkit" / "tests" / "fixtures"))


@pytest.fixture(scope="session")
def assembler() -> Path:
    from build import BuildError, find_assembler
    try:
        return find_assembler()
    except BuildError as e:
        pytest.skip(str(e))


@pytest.fixture(scope="session")
def cartridge(tmp_path_factory) -> Path:
    """The synthetic test cartridge, written to a private temp dir.

    Never the real ROM: the test suite has to run in CI, where no
    copyrighted cartridge exists and none may be committed.
    """
    from make_fixture import build_fixture_rom
    path = tmp_path_factory.mktemp("cart") / "fixture.md"
    path.write_bytes(build_fixture_rom())
    return path


@pytest.fixture(scope="session")
def lock(cartridge, tmp_path_factory) -> Path:
    data = cartridge.read_bytes()
    path = tmp_path_factory.mktemp("lock") / "rom-lock.json"
    path.write_text(json.dumps({"revisions": [{
        "id": "fixture", "title": "Synthetic test cartridge",
        "size": len(data),
        "sha1": hashlib.sha1(data).hexdigest(),
        "sha256": hashlib.sha256(data).hexdigest(),
        "verified": "Generated by toolkit/tests/fixtures/make_fixture.py",
    }]}))
    return path


def write_regions(path: Path, regions: list[dict], rom: str = "fixture") -> Path:
    path.write_text(json.dumps({"rom": rom, "regions": regions}))
    return path
